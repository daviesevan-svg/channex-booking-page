#!/usr/bin/env node
// Translation workflow: one spreadsheet per language in, code out.
//
//   npm run i18n:export -- sk            → translations/sk.csv (every guest string)
//   npm run i18n:export -- de --missing  → only the rows German still lacks
//   npm run i18n:export -- de --admin    → the admin UI instead of the guest side
//   npm run i18n:import -- translations/sk.csv   → validates, writes the code, syncs
//   npm run i18n:sync                    → regenerate the language registries
//
// The CSV (UTF-8, opens in Excel / Google Sheets / any CAT tool) has one row per
// string: id, context, english, translation, notes. A translator fills in the
// `translation` column and sends the file back; nothing else needs touching.
//
// Where each id lands:
//   ui.<key>            app/lib/locales/<lang>.ts          guest UI labels
//   search.* page.* legal.* meta.*
//                       app/lib/locales/copy/<lang>.json   editable page defaults
//   email.<id>.<field>  app/lib/locales/emails/<lang>.json guest email defaults
//   admin.<key>         app/lib/admin-locales/<lang>.ts    admin UI (--admin)
//
// A guest language is "installed" by having copy/<lang>.json; `sync` then wires
// it into the language picker, the server dictionary registry, the email
// defaults and the date-fns locale map. No hand edits. (A new ADMIN language
// still needs registering in app/lib/admin-i18n.ts; import says so.)
//
// Plurals: English has `_one`/`_other`. Languages with more forms (Slovak and
// Czech: 1 / 2–4 / 5+) get extra rows such as `ui.night_few`; the translator
// picks the form via Intl.PluralRules, so export offers exactly the forms the
// language uses for whole numbers.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LIB = path.join(ROOT, "app/lib");
const LOCALES = path.join(LIB, "locales");
const ADMIN_LOCALES = path.join(LIB, "admin-locales");
const COPY_DIR = path.join(LOCALES, "copy");
const EMAIL_DIR = path.join(LOCALES, "emails");
const jiti = createJiti(import.meta.url, { alias: { "~": path.join(ROOT, "app") }, moduleCache: false });

const PAGE_IDS = ["results", "detail", "checkout", "extras", "confirmation"];
const EMAIL_IDS = ["booking_confirmation", "booking_cancellation", "booking_failed", "booking_failed_refund_pending", "review_request"];
const LANG_FILE = /^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$/;
const GENERATED = "// GENERATED by `npm run i18n:sync` — do not edit; see scripts/i18n.mjs.";

// ── plural forms ─────────────────────────────────────────────────────────────

/** The runtime's rule (app/lib/i18n.ts `pluralForm`), mirrored: 1 → one, else the
 *  CLDR category, with "one" for any other number folded into "other". */
function pluralForm(lang, n) {
  if (n === 1) return "one";
  let cat = "other";
  try {
    cat = new Intl.PluralRules(lang).select(n);
  } catch {}
  return cat === "one" ? "other" : cat;
}

/** Forms a language uses for whole numbers, with sample counts for the notes. */
function pluralForms(lang) {
  const forms = new Map();
  for (let n = 0; n <= 120; n++) {
    const f = pluralForm(lang, n);
    if (!forms.has(f)) forms.set(f, []);
    if (forms.get(f).length < 5) forms.get(f).push(n);
  }
  return forms;
}

// ── CSV ──────────────────────────────────────────────────────────────────────

const csvCell = (v) => (/[",\n\r]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);

function toCsv(rows) {
  // BOM so Excel reads UTF-8 (Cyrillic, Thai, diacritics) instead of mojibake.
  return "﻿" + rows.map((r) => r.map((c) => csvCell(String(c ?? ""))).join(",")).join("\r\n") + "\r\n";
}

function parseCsv(text) {
  text = text.replace(/^﻿/, "");
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += ch;
  }
  if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim() !== ""));
}

// ── sources ──────────────────────────────────────────────────────────────────

const readJson = (f, fallback) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : fallback);
const placeholders = (s) => (String(s).match(/\{\w+\}/g) ?? []).sort().join(" ");

async function loadDict(file) {
  if (!fs.existsSync(file)) return {};
  return { ...(await jiti.import(file, { default: true })) };
}

/** English for every guest string, keyed by CSV id, with a context label. */
async function englishGuest() {
  const content = await jiti.import(path.join(LIB, "content.ts"));
  const emails = await jiti.import(path.join(LIB, "email-defaults.server.ts"));
  const eu = await jiti.import(path.join(LIB, "eu-consumer.ts"));
  const rows = [];
  rows.push({ id: "meta.label", context: "Language picker", en: "English", note: "This language's name IN this language (e.g. Slovenčina)." });
  rows.push({ id: "meta.flag", context: "Language picker", en: "🇬🇧", note: "One flag emoji shown next to the name." });
  for (const r of await dictRows(path.join(LOCALES, "en.ts"), "ui")) rows.push(r);
  const search = content.searchDefaults("en");
  for (const k of ["heading", "intro", "promoText", "searchButton"]) rows.push({ id: `search.${k}`, context: "Search box (home page)", en: search[k] });
  for (const p of PAGE_IDS) for (const [k, v] of Object.entries(content.pageDefaults(p, "en"))) rows.push({ id: `page.${p}.${k}`, context: `Page: ${p}`, en: v });
  for (const id of EMAIL_IDS) for (const [k, v] of Object.entries(emails.emailDefaults(id, "en"))) if (v) rows.push({ id: `email.${id}.${k}`, context: `Email: ${id.replace(/_/g, " ")}`, en: v, note: k === "intro" || k === "outro" ? "Email body; blank lines separate paragraphs." : "" });
  rows.push({ id: "legal.euOrderButton", context: "Checkout button (EU law)", en: eu.payButtonLabel("en"), note: "Legally required wording: must say plainly that booking means paying (EU Directive 2011/83, Art. 8(2)). Keep it blunt." });
  return rows;
}

/** One row per key of an English dictionary file, with the nearest section
 *  comment above it as context. */
async function dictRows(file, prefix) {
  const dict = await loadDict(file);
  const context = new Map();
  let section = "";
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const c = line.match(/^\s*\/\/\s*-+\s*(.+?)\s*-+\s*$/) || line.match(/^\s{2}\/\/\s*(.+)$/);
    if (c) section = c[1];
    const k = line.match(/^\s*([A-Za-z_$][\w$]*):/);
    if (k) context.set(k[1], section);
  }
  return Object.entries(dict).map(([k, v]) => ({ id: `${prefix}.${k}`, context: context.get(k) ?? "", en: v }));
}

/** Current translations of a language, keyed by CSV id. */
async function currentGuest(lang) {
  const out = {};
  const dict = await loadDict(path.join(LOCALES, `${lang}.ts`));
  for (const [k, v] of Object.entries(dict)) out[`ui.${k}`] = v;
  const copy = readJson(path.join(COPY_DIR, `${lang}.json`), {});
  if (copy.label) out["meta.label"] = copy.label;
  if (copy.flag) out["meta.flag"] = copy.flag;
  for (const [k, v] of Object.entries(copy.search ?? {})) out[`search.${k}`] = v;
  for (const [p, fields] of Object.entries(copy.pages ?? {})) for (const [k, v] of Object.entries(fields)) out[`page.${p}.${k}`] = v;
  if (copy.euOrderButton) out["legal.euOrderButton"] = copy.euOrderButton;
  const emails = readJson(path.join(EMAIL_DIR, `${lang}.json`), {});
  for (const [id, fields] of Object.entries(emails)) for (const [k, v] of Object.entries(fields)) out[`email.${id}.${k}`] = v;
  return out;
}

async function currentAdmin(lang) {
  const dict = await loadDict(path.join(ADMIN_LOCALES, `${lang}.ts`));
  return Object.fromEntries(Object.entries(dict).map(([k, v]) => [`admin.${k}`, v]));
}

/** Expand `x_one`/`x_other` English rows into the language's plural forms. */
function withPluralRows(rows, lang) {
  const forms = pluralForms(lang);
  const out = [];
  for (const r of rows) {
    const m = r.id.match(/^(.*)_(one|other)$/);
    if (!m) { out.push(r); continue; }
    if (m[2] === "one") {
      out.push({ ...r, note: join(r.note, `Plural form for exactly 1.`) });
      continue;
    }
    // At the `_other` row emit every extra form the language has, then `_other`.
    for (const [form, samples] of forms) {
      if (form === "one" || form === "other") continue;
      out.push({ ...r, id: `${m[1]}_${form}`, note: join(r.note, `Plural form for counts like ${samples.join(", ")}… (English shows the plural).`) });
    }
    out.push({ ...r, note: join(r.note, `Plural form for counts like ${(forms.get("other") ?? []).join(", ")}…`) });
  }
  return out;
}

const join = (...xs) => xs.filter(Boolean).join(" ");

function noteFor(r) {
  const ph = placeholders(r.en);
  return join(r.note, ph ? `Keep ${ph} exactly as written.` : "");
}

// ── export ───────────────────────────────────────────────────────────────────

async function cmdExport(lang, flags) {
  if (!lang || !LANG_FILE.test(lang) || lang === "en") die("Usage: npm run i18n:export -- <lang> [--missing] [--admin] [--out file.csv]");
  const admin = flags.has("--admin");
  const english = admin ? await dictRows(path.join(ADMIN_LOCALES, "en.ts"), "admin") : await englishGuest();
  const current = admin ? await currentAdmin(lang) : await currentGuest(lang);
  let rows = withPluralRows(english, lang);
  if (flags.has("--missing")) rows = rows.filter((r) => !current[r.id]);
  const outFile = flags.get("--out") ?? path.join(ROOT, "translations", `${lang}${admin ? "-admin" : ""}.csv`);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  const header = ["id", "context", "english", "translation", "notes"];
  fs.writeFileSync(outFile, toCsv([header, ...rows.map((r) => [r.id, r.context, r.en, current[r.id] ?? "", noteFor(r)])]));
  const done = rows.filter((r) => current[r.id]).length;
  console.log(`${path.relative(ROOT, outFile)}: ${rows.length} rows, ${done} already translated, ${rows.length - done} to do.`);
  console.log(`Send it to the translator: fill in the "translation" column only, then run\n  npm run i18n:import -- ${path.relative(ROOT, outFile)}`);
}

// ── import ───────────────────────────────────────────────────────────────────

async function cmdImport(file, flags) {
  if (!file || !fs.existsSync(file)) die("Usage: npm run i18n:import -- translations/<lang>.csv [--lang xx]");
  const lang = flags.get("--lang") ?? path.basename(file).replace(/(-admin)?\.csv$/i, "");
  if (!LANG_FILE.test(lang) || lang === "en") die(`Can't tell the language from "${path.basename(file)}" — name it <lang>.csv or pass --lang.`);
  const rows = parseCsv(fs.readFileSync(file, "utf8"));
  const head = rows.shift()?.map((h) => h.trim().toLowerCase()) ?? [];
  const col = { id: head.indexOf("id"), tr: head.indexOf("translation") };
  if (col.id < 0 || col.tr < 0) die('The CSV needs "id" and "translation" columns (keep the header row from the export).');

  const admin = rows.some((r) => r[col.id]?.startsWith("admin."));
  const english = withPluralRows(admin ? await dictRows(path.join(ADMIN_LOCALES, "en.ts"), "admin") : await englishGuest(), lang);
  const enById = new Map(english.map((r) => [r.id, r.en]));

  const errors = [];
  const incoming = {};
  for (const r of rows) {
    const id = (r[col.id] ?? "").trim();
    const value = (r[col.tr] ?? "").replace(/\r\n/g, "\n");
    if (!id || !value.trim()) continue;
    if (!enById.has(id)) { errors.push(`${id}: unknown id (from an older export, or a typo?)`); continue; }
    if (id !== "meta.flag" && placeholders(value) !== placeholders(enById.get(id))) {
      errors.push(`${id}: placeholders ${placeholders(value) || "(none)"} ≠ English ${placeholders(enById.get(id)) || "(none)"}`);
      continue;
    }
    incoming[id] = value.trim() === value ? value : value.trim();
  }
  if (errors.length) die(`Nothing written — fix these rows first:\n  ${errors.join("\n  ")}`);

  const merged = { ...(admin ? await currentAdmin(lang) : await currentGuest(lang)), ...incoming };
  if (admin) {
    writeDict(path.join(ADMIN_LOCALES, "en.ts"), path.join(ADMIN_LOCALES, `${lang}.ts`), lang, pick(merged, "admin."), "admin");
    const registered = fs.readFileSync(path.join(LIB, "admin-i18n.ts"), "utf8").includes(`"${lang}"`);
    if (!registered) console.log(`\n${lang} is not an admin language yet: add it to AdminLang / ADMIN_LANGS / adminLangFromRequest in app/lib/admin-i18n.ts and to app/lib/admin-i18n-locales.server.ts.`);
  } else {
    if (!merged["meta.label"] || !merged["meta.flag"]) die("meta.label and meta.flag are required for a guest language (its own name, and a flag emoji).");
    writeDict(path.join(LOCALES, "en.ts"), path.join(LOCALES, `${lang}.ts`), lang, pick(merged, "ui."), "guest");
    writeCopy(lang, merged);
    writeEmails(lang, merged);
    await cmdSync();
  }
  const missing = english.filter((r) => !merged[r.id]);
  console.log(`\n${lang}: imported ${Object.keys(incoming).length} rows; ${english.length - missing.length}/${english.length} translated.`);
  if (missing.length) console.log(`Still in English (${missing.length}): ${missing.slice(0, 12).map((r) => r.id).join(", ")}${missing.length > 12 ? ", …" : ""}\n  npm run i18n:export -- ${lang}${admin ? " --admin" : ""} --missing   lists them all.`);
}

const pick = (obj, prefix) => Object.fromEntries(Object.entries(obj).filter(([k]) => k.startsWith(prefix)).map(([k, v]) => [k.slice(prefix.length), v]));

/** Rewrite a dictionary file from the ENGLISH file's layout — same key order,
 *  same section comments — so every language diffs line-for-line with English.
 *  Keys without a translation are left out (English fills them at runtime);
 *  extra plural forms (`_few`, `_many`) follow their `_other` key. */
function writeDict(enFile, outFile, lang, values, kind) {
  const keep = fs.existsSync(outFile) ? leadingComment(fs.readFileSync(outFile, "utf8")) : "";
  const header = keep || (kind === "guest"
    ? `// ${lang} guest UI labels. Written by \`npm run i18n:import\`; edit the CSV, not this file, so\n// the next import doesn't undo it. Missing keys fall back to English.\n`
    : `// ${lang} admin-UI labels. Written by \`npm run i18n:import\`. Loaded on the server only —\n// see app/lib/admin-i18n.ts.\n`);
  const NAME = lang.toUpperCase().replace(/-/g, "_");
  const lines = fs.readFileSync(enFile, "utf8").split("\n");
  const out = [];
  let inBody = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!inBody) {
      if (/^const EN\b/.test(line)) {
        if (kind === "guest") out.push('import type { Dict } from "../i18n-dict";', "");
        out.push(line.replace(/^const EN\b/, `const ${NAME}`));
        inBody = true;
      }
      continue;
    }
    if (/^\};/.test(line)) { out.push(line, "", `export default ${NAME};`, ""); break; }
    const prop = line.match(/^(\s*)([A-Za-z_$][\w$]*):(.*)$/);
    if (!prop) { out.push(line); continue; }
    if (prop[3].trim() === "") i++; // value on the next line
    const [, indent, key] = prop;
    if (values[key] != null) out.push(`${indent}${key}: ${JSON.stringify(values[key])},`);
    const base = key.match(/^(.*)_other$/)?.[1];
    if (base) for (const form of ["zero", "two", "few", "many"]) if (values[`${base}_${form}`] != null) out.push(`${indent}${base}_${form}: ${JSON.stringify(values[`${base}_${form}`])},`);
  }
  fs.writeFileSync(outFile, header + "\n" + out.join("\n").replace(/\n{3,}/g, "\n\n"));
  console.log(`wrote ${path.relative(ROOT, outFile)}`);
}

function leadingComment(src) {
  const m = src.match(/^((?:\/\/[^\n]*\n)+)/);
  return m ? m[1] : "";
}

function writeCopy(lang, v) {
  const copy = { label: v["meta.label"], flag: v["meta.flag"] };
  const search = pick(v, "search.");
  if (Object.keys(search).length) copy.search = search;
  copy.pages = {};
  for (const p of PAGE_IDS) {
    const fields = pick(v, `page.${p}.`);
    if (Object.keys(fields).length) copy.pages[p] = fields;
  }
  if (v["legal.euOrderButton"]) copy.euOrderButton = v["legal.euOrderButton"];
  fs.mkdirSync(COPY_DIR, { recursive: true });
  fs.writeFileSync(path.join(COPY_DIR, `${lang}.json`), JSON.stringify(copy, null, 2) + "\n");
  console.log(`wrote app/lib/locales/copy/${lang}.json`);
}

function writeEmails(lang, v) {
  const emails = {};
  for (const id of EMAIL_IDS) {
    const fields = pick(v, `email.${id}.`);
    if (Object.keys(fields).length) emails[id] = fields;
  }
  fs.mkdirSync(EMAIL_DIR, { recursive: true });
  fs.writeFileSync(path.join(EMAIL_DIR, `${lang}.json`), JSON.stringify(emails, null, 2) + "\n");
  console.log(`wrote app/lib/locales/emails/${lang}.json`);
}

// ── sync: the generated registries ───────────────────────────────────────────

const ident = (lang) => lang.replace(/-(\w)/g, (_, c) => c.toUpperCase());

async function cmdSync() {
  const langs = fs.readdirSync(COPY_DIR).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).filter((l) => LANG_FILE.test(l) && l !== "en").sort();
  for (const l of langs) {
    if (!fs.existsSync(path.join(LOCALES, `${l}.ts`))) die(`copy/${l}.json exists but locales/${l}.ts doesn't — import the language's CSV.`);
    if (!fs.existsSync(path.join(EMAIL_DIR, `${l}.json`))) fs.writeFileSync(path.join(EMAIL_DIR, `${l}.json`), "{}\n");
  }
  const all = ["en", ...langs];
  const write = (file, body) => {
    const target = path.join(LOCALES, file);
    const next = `${GENERATED}\n${body}`;
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== next) {
      fs.writeFileSync(target, next);
      console.log(`synced app/lib/locales/${file}`);
    }
  };

  write("copy.ts", `// Per-language page/search defaults, picker label and EU button wording.
// Small, and needed by client-reachable code (content.ts, eu-consumer.ts).

import type { LocaleCopy } from "./types";
${langs.map((l) => `import ${ident(l)} from "./copy/${l}.json";`).join("\n")}

export const LOCALE_COPY: Record<string, LocaleCopy> = { ${langs.map(ident).join(", ")} };
`);

  write("emails.server.ts", `// Per-language guest email defaults. Server only (email-defaults.server.ts).

import type { LocaleEmails } from "./types";
${langs.map((l) => `import ${ident(l)} from "./emails/${l}.json";`).join("\n")}

export const LOCALE_EMAILS: Record<string, LocaleEmails> = { ${langs.map(ident).join(", ")} };
`);

  write("dicts.server.ts", `// Every guest UI dictionary. Server only — see i18n-locales.server.ts for why the
// browser must never import this.

import type { Dict } from "../i18n-dict";
${all.map((l) => `import ${ident(l)} from "./${l}";`).join("\n")}

export const GUEST_DICTS: Record<string, Dict> = { ${all.map(ident).join(", ")} };
`);

  // date-fns ships most locales; a language it lacks formats dates in British English.
  const dfn = (l) => (l === "en" ? "enGB" : ident(l.replace("-", "")));
  const hasDfn = (l) => l === "en" || fs.existsSync(path.join(ROOT, "node_modules/date-fns/locale", `${dfn(l)}.js`));
  const missing = all.filter((l) => !hasDfn(l));
  if (missing.length) console.log(`date-fns has no locale for ${missing.join(", ")}; dates fall back to en-GB.`);
  const withDfn = all.filter(hasDfn);
  write("date-locales.ts", `// date-fns locale per guest language (bundled for the browser, like before).

import { ${[...new Set(withDfn.map(dfn))].sort().join(", ")}, type Locale } from "date-fns/locale";

export const DATE_LOCALES: Record<string, Locale> = { ${withDfn.map((l) => (l === dfn(l) ? l : `${JSON.stringify(l).replace(/^"([a-z]+)"$/, "$1")}: ${dfn(l)}`)).join(", ")} };
`);
}

// ── main ─────────────────────────────────────────────────────────────────────

function die(msg) {
  console.error(msg);
  process.exit(1);
}

const [cmd, ...rest] = process.argv.slice(2);
const flags = new Map();
const pos = [];
for (let i = 0; i < rest.length; i++) {
  if (rest[i] === "--out" || rest[i] === "--lang") flags.set(rest[i], rest[++i]);
  else if (rest[i].startsWith("--")) flags.set(rest[i], true);
  else pos.push(rest[i]);
}
flags.has = Map.prototype.has.bind(flags);

if (cmd === "export") await cmdExport(pos[0], flags);
else if (cmd === "import") await cmdImport(pos[0], flags);
else if (cmd === "sync") await cmdSync();
else die("Usage: node scripts/i18n.mjs export <lang> [--missing] [--admin] | import <file.csv> | sync");
